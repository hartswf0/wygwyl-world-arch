#!/usr/bin/env python3
"""
ply_to_splat.py — Convert DepthPro metric point clouds (points.ply) to 3D Gaussian Splats.

Outputs:
  1. scene.splat  — 32 bytes per Gaussian (antimatter15 / WebGL format)
  2. scene_gs.ply — Standard 3D Gaussian Splatting PLY (Kerbl et al., SuperSplat, Blender, Nerfstudio)

Usage:
  python3 shots/ply_to_splat.py --match 018da7e9     # Single shot
  python3 shots/ply_to_splat.py --all                # All 81 shots
"""
import argparse, glob, json, math, os, re, sys
import numpy as np

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
OUT_DIR = os.path.join(ROOT, "shots", "out")


def load_ply_points(path):
    """Parses binary_little_endian 1.0 PLY generated by analyze.py (x, y, z, red, green, blue)."""
    with open(path, "rb") as f:
        header = ""
        while True:
            line = f.readline().decode("ascii", errors="ignore")
            header += line
            if "end_header" in line:
                break
        n_verts = 0
        for l in header.split("\n"):
            if l.startswith("element vertex"):
                n_verts = int(l.split()[-1])
        if n_verts == 0:
            return None, None
        data = np.frombuffer(f.read(), dtype=[("p", "<f4", 3), ("c", "u1", 3)], count=n_verts)
        return data["p"], data["c"]


def export_splat(pts, cols, focal_px, step, dst_splat):
    """
    Antimatter15 32-byte .splat binary format:
      pos:   3 x float32 (12 bytes)
      scale: 3 x float32 (12 bytes)
      rgba:  4 x uint8   (4 bytes)
      rot:   4 x uint8   (4 bytes) [w, x, y, z] -> [255, 128, 128, 128]
    """
    n = len(pts)
    z = np.maximum(np.abs(pts[:, 2]), 0.2)
    # Metric Gaussian footprint: footprint radius at depth z
    focal = float(focal_px) if focal_px else 1200.0
    r = (z * (step / focal) * 1.35).astype(np.float32)
    scales = np.column_stack([r, r, r])

    rgba = np.column_stack([cols, np.full((n, 1), 255, dtype=np.uint8)])
    rots = np.full((n, 4), [255, 128, 128, 128], dtype=np.uint8)

    splat_dtype = np.dtype([
        ("pos", "<f4", 3),
        ("scale", "<f4", 3),
        ("rgba", "u1", 4),
        ("rot", "u1", 4)
    ])
    buf = np.empty(n, dtype=splat_dtype)
    buf["pos"] = pts
    buf["scale"] = scales
    buf["rgba"] = rgba
    buf["rot"] = rots

    with open(dst_splat, "wb") as f:
        f.write(buf.tobytes())
    return os.path.getsize(dst_splat)


def export_gs_ply(pts, cols, focal_px, step, dst_ply):
    """
    Standard Inria / 3DGS PLY format readable by SuperSplat, Nerfstudio, Splatpost, Blender:
      x, y, z, nx, ny, nz, f_dc_0, f_dc_1, f_dc_2, opacity, scale_0, scale_1, scale_2, rot_0, rot_1, rot_2, rot_3
    """
    n = len(pts)
    z = np.maximum(np.abs(pts[:, 2]), 0.2)
    focal = float(focal_px) if focal_px else 1200.0
    r = (z * (step / focal) * 1.35).astype(np.float32)
    log_scale = np.log(np.maximum(r, 1e-5))

    # Spherical Harmonics DC component: SH_C0 = 0.28209479177387814
    SH_C0 = 0.28209479177387814
    rgb_f = cols.astype(np.float32) / 255.0
    f_dc = (rgb_f - 0.5) / SH_C0

    # Opacity logit: sigmoid(5.0) ~ 0.993
    opacity_logit = np.full(n, 5.0, dtype=np.float32)

    # Rotation: unit quaternion [w, x, y, z] = [1, 0, 0, 0]
    rots = np.zeros((n, 4), dtype=np.float32)
    rots[:, 0] = 1.0

    norms = np.zeros((n, 3), dtype=np.float32)

    header = (
        "ply\n"
        "format binary_little_endian 1.0\n"
        f"element vertex {n}\n"
        "property float x\nproperty float y\nproperty float z\n"
        "property float nx\nproperty float ny\nproperty float nz\n"
        "property float f_dc_0\nproperty float f_dc_1\nproperty float f_dc_2\n"
        "property float opacity\n"
        "property float scale_0\nproperty float scale_1\nproperty float scale_2\n"
        "property float rot_0\nproperty float rot_1\nproperty float rot_2\nproperty float rot_3\n"
        "end_header\n"
    )

    gs_dtype = np.dtype([
        ("pos", "<f4", 3),
        ("norm", "<f4", 3),
        ("f_dc", "<f4", 3),
        ("opacity", "<f4"),
        ("scale", "<f4", 3),
        ("rot", "<f4", 4)
    ])

    buf = np.empty(n, dtype=gs_dtype)
    buf["pos"] = pts
    buf["norm"] = norms
    buf["f_dc"] = f_dc
    buf["opacity"] = opacity_logit
    buf["scale"] = np.column_stack([log_scale, log_scale, log_scale])
    buf["rot"] = rots

    with open(dst_ply, "wb") as f:
        f.write(header.encode("ascii"))
        f.write(buf.tobytes())
    return os.path.getsize(dst_ply)


def process_shot(sid, verbose=True):
    od = os.path.join(OUT_DIR, sid)
    ply_p = os.path.join(od, "points.ply")
    sj_p = os.path.join(od, "shot.json")
    if not os.path.exists(ply_p):
        return None

    focal_px = 1200.0
    if os.path.exists(sj_p):
        try:
            sj = json.load(open(sj_p))
            focal_px = sj.get("camera", {}).get("focal_px", 1200.0)
        except Exception:
            pass

    pts, cols = load_ply_points(ply_p)
    if pts is None:
        return None

    splat_path = os.path.join(od, "scene.splat")
    gs_ply_path = os.path.join(od, "scene_gs.ply")

    sz_splat = export_splat(pts, cols, focal_px, step=3, dst_splat=splat_path)
    sz_ply = export_gs_ply(pts, cols, focal_px, step=3, dst_ply=gs_ply_path)

    if verbose:
        print(f"[{sid[:12]}] {len(pts):,} points -> splat: {sz_splat/1024/1024:.2f}MB, 3dgs-ply: {sz_ply/1024/1024:.2f}MB")
    return {"id": sid, "points": len(pts), "splat_mb": round(sz_splat / 1024 / 1024, 2)}


def main():
    ap = argparse.ArgumentParser(description="Convert DepthPro points.ply to 3D Gaussian Splats")
    ap.add_argument("--all", action="store_true", help="Process all analyzed shots")
    ap.add_argument("--match", nargs="*", help="Filter shot IDs by substring")
    a = ap.parse_args()

    shots = sorted([os.path.basename(os.path.dirname(p)) for p in glob.glob(os.path.join(OUT_DIR, "*", "points.ply"))])
    if a.match:
        shots = [s for s in shots if any(m in s for m in a.match)]
    elif not a.all:
        # Default sample across 6 core districts
        default_pats = ["018da7e9", "0240b488", "05a0677a", "06881630", "08fe12af", "d3d25411"]
        shots = [s for s in shots if any(p in s for p in default_pats)]

    print(f"Converting {len(shots)} shots to 3D Gaussian Splats (.splat & scene_gs.ply)...")
    results = []
    for sid in shots:
        r = process_shot(sid)
        if r: results.append(r)
    print(f"Done. Successfully generated Gaussian assets for {len(results)} shots.")


if __name__ == "__main__":
    main()
