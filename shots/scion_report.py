#!/usr/bin/env python3
"""Render shots/scion/SCION_AUDIT.md from the compiled state graphs.

The numbers come straight from shots/scion/state/*.json (written by
scion_compile.py), so the report cannot drift from the data.
"""
import glob
import json
import os
from collections import Counter

HERE = os.path.dirname(os.path.abspath(__file__))
OUT = os.path.join(HERE, "scion")

GATES = ["G1_silhouette", "G2_volume", "G3_contact", "G4_arcs", "G5_vitality"]
ICON = {"PASS": "✅ PASS", "FAIL": "❌ FAIL", "N/A": "— N/A"}


def main():
    states = [json.load(open(f)) for f in sorted(glob.glob(os.path.join(OUT, "state", "*.json")))]
    idx = json.load(open(os.path.join(OUT, "index.json")))
    tally = {g: Counter(s["gates"][g]["status"] for s in states) for g in GATES}
    flaws = Counter(s["audit"]["highest_leverage_flaw"] for s in states)
    signs = Counter(b["sign"] for s in states for b in s["dramatic"]["beats"])
    L = []
    w = L.append
    w("# SCION audit: the 14 WYGWYL cel sequences\n")
    w("Generated by `shots/scion_report.py` from the State Graphs that `shots/scion_compile.py` writes.")
    w("Studio: [`shots/scion.html`](scion.html) · Cineosis export: [`cineosis_export.json`](scion/cineosis_export.json)\n")
    w("> The footage is generated video run through a cel filter. SCION **measures and re-times** it. It does not invent drawings, except for the drawn keys on "
      + ", ".join(idx.get("drawn", [])) + ". Causal roles and Cineosis signs are heuristic labels computed from the motion; the gates are measurements.\n")

    w("## Gate tally (14 sequences)\n")
    w("| Gate | PASS | FAIL | N/A | What it measures |")
    w("| :-- | --: | --: | --: | :-- |")
    what = {
        "G1_silhouette": "P2 mask solidity, components, area at each pipeline key",
        "G2_volume": "area × z² drift between adjacent keys in one shot (±5%)",
        "G3_contact": "foot-point slide on recovered ground, camera-compensated",
        "G4_arcs": "centroid path reversals, speed variance, breakdown timing asymmetry",
        "G5_vitality": "cel vs source: motion correlation, punch, line, boil on still pixels",
    }
    for g in GATES:
        t = tally[g]
        w(f"| {g} | {t['PASS']} | {t['FAIL']} | {t['N/A']} | {what[g]} |")
    w("")
    w("**Highest-leverage flaw** (first failing gate in order G5 → G1 → G3 → G2 → G4): " + ", ".join(f"`{k}` × {v}" for k, v in flaws.most_common()) + "\n")
    w("**Cineosis sign distribution across all beats:** " + ", ".join(f"{k} {v}" for k, v in signs.most_common()) + "\n")

    w("## The hard truth\n")
    g5 = [s["gates"]["G5_vitality"] for s in states]
    boil = sorted(x["boil_static"] for x in g5 if x.get("boil_static"))
    corr = sorted(x["motion_corr"] for x in g5 if x.get("motion_corr") is not None)
    w(f"- **The cel pass boils.** On pixels that do not move in the source, the cel frames change {boil[0]:.1f}–{boil[-1]:.1f}× as much (median {boil[len(boil)//2]:.1f}×). "
      "The cel filter runs frame by frame, so the flats re-segment on every frame. That is unmotivated volume pulsing, which the prompt calls fatal.")
    w(f"- **Motion structure is only partly kept.** The correlation between source and cel frame-change curves is {corr[0]:.2f}–{corr[-1]:.2f} (median {corr[len(corr)//2]:.2f}). "
      "Where it is low, the flicker drowns out the real action.")
    g2 = [s["gates"]["G2_volume"] for s in states if s["gates"]["G2_volume"]["status"] != "N/A"]
    if g2:
        med = sorted(x["median_dev"] for x in g2)
        w(f"- **Volume is not conserved between keys.** The median depth-scaled area drift per sequence is {med[0]*100:.0f}–{med[-1]*100:.0f}%, against a ±5% tolerance. "
          "Plane 2 masks come from per-key segmentation, so the 'character' changes identity as well as shape.")
    w("- **The fix order** is therefore not cosmetic: (1) stabilise the cel temporally by propagating flats along optical flow and re-segmenting only on keys, "
      "(2) track one P2 identity through each shot instead of re-segmenting per key, then (3) re-run the gates. Re-timing in the studio is safe meanwhile, because it moves exposures without repainting.\n")

    w("## Per sequence\n")
    w("| # | Title | Beats · cuts | Causal chain | G1 | G2 | G3 | G4 | G5 | Flaw |")
    w("| :-- | :-- | :-- | :-- | :-- | :-- | :-- | :-- | :-- | :-- |")
    for s in states:
        chain = " → ".join(b["role"].split("_")[0][:5] for b in s["dramatic"]["beats"])
        gs = " | ".join(ICON.get(s["gates"][g]["status"], s["gates"][g]["status"]) for g in GATES)
        w(f"| {s['num']} | [{s['title']}](scion.html?poem={s['id']}) | {len(s['dramatic']['beats'])} · {len(s['cuts'])} | {chain} | {gs} | `{s['audit']['highest_leverage_flaw'] or '—'}` |")
    w("")
    for s in states:
        g = s["gates"]
        w(f"### {s['num']} · {s['title']}\n")
        if s.get("tagline"):
            w(f"*{s['tagline']}* · {s.get('district') or ''}\n")
        w(f"- **Beats:** " + " · ".join(f"{b['id']} {b['role']} ({b['sign']}, {b['dur_24']}f)" for b in s["dramatic"]["beats"]))
        ft = s["dramatic"].get("flip_test")
        if ft:
            w(f"- **Key-only flip test:** {'reads' if ft['reads'] else 'does not read'} (mean key change {ft['mean_key_change']})")
        w(f"- **X-sheet:** {s['xsheet']['drawings']} drawings over {s['frames']} source frames · exposures {s['xsheet']['exposure_mix']}")
        g1 = g["G1_silhouette"]
        w(f"- **G1** {g1['status']}: " + (f"pass rate {g1['pass_rate']}" if g1.get("keys") else g1.get("reason", "")))
        g2 = g["G2_volume"]
        w(f"- **G2** {g2['status']}: " + (f"median drift {g2['median_dev']*100:.0f}% over {len(g2['pairs'])} key pairs" if g2.get("pairs") else g2.get("reason", "")))
        g3 = g["G3_contact"]
        w(f"- **G3** {g3['status']}: " + (f"pass rate {g3['pass_rate']} over {len(g3['pairs'])} pinned pairs" if g3.get("pairs") else g3.get("reason", "")))
        g4 = g["G4_arcs"]
        w(f"- **G4** {g4['status']}: zig-zag {g4['zigzag_rate']}, speed CV {g4['speed_cv']}, linear breakdowns {g4['linear_breakdown_rate']}")
        g5 = g["G5_vitality"]
        w(f"- **G5** {g5['status']} → {g5['verdict']}: motion corr {g5['motion_corr']}, punch {g5['punch_ratio']}, line {g5['edge_ratio']}, boil on still px {g5.get('boil_static')}×"
          + (f". {'; '.join(g5['reasons'])}" if g5.get("reasons") else ""))
        w(f"- **Fix:** {s['audit']['fix']}\n")

    with open(os.path.join(OUT, "SCION_AUDIT.md"), "w") as f:
        f.write("\n".join(L))
    print("wrote", os.path.join(OUT, "SCION_AUDIT.md"))


if __name__ == "__main__":
    main()
